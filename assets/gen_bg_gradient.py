"""
Pre-renders the desk panel's background: a soft off-center radial blob
(bright cyan-blue core -> purple -> near-black), baked once into RGB565
pixel data for an LVGL lv_img_dsc_t C source file.

This replaces a runtime LV_DITHER_ERR_DIFF style gradient (recomputed on
every redraw -- expensive on this MCU, especially during tileview scroll
animations) with a static bitmap that's just blitted.

No dithering: every scheme tried (per-row error diffusion, uniform noise,
triangular noise) was clearly visible on real hardware -- either as a
structured wave artifact or as plain grain. Plain RGB565 rounding, no
noise added.
"""

import math

W, H = 800, 480

# Blob center sits off-canvas upper-left, like the reference image, so
# only its lower-right falloff is visible on screen.
CENTER = (60, -60)
RADIUS = 950  # distance (px) at which the blob fully fades to the outer color

STOPS = [
    (0.0, (0x35, 0xC5, 0xF2)),  # bright cyan-blue core
    (0.45, (0x5B, 0x21, 0xA8)), # purple
    (1.0, (0x0A, 0x0A, 0x10)),  # near-black
]


def stops_color(t: float) -> tuple[float, float, float]:
    for i in range(len(STOPS) - 1):
        t0, c0 = STOPS[i]
        t1, c1 = STOPS[i + 1]
        if t <= t1 or i == len(STOPS) - 2:
            local_t = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            local_t = max(0.0, min(1.0, local_t))
            return tuple(c0[k] + (c1[k] - c0[k]) * local_t for k in range(3))
    return STOPS[-1][1]


def gradient_color(x: int, y: int) -> tuple[float, float, float]:
    dist = math.hypot(x - CENTER[0], y - CENTER[1])
    t = max(0.0, min(1.0, dist / RADIUS))
    return stops_color(t)


def quantize(value: float, levels: int) -> int:
    # No dithering: every noise scheme tried (per-row error diffusion,
    # full-amplitude uniform, triangular at 55%) was clearly visible on
    # real hardware -- as a structured wave artifact or as plain grain,
    # confirmed in a real photo of the panel. This gradient's colors are
    # close enough in the low end of the range that plain RGB565 rounding
    # doesn't band noticeably; a smooth, slightly-imperfect gradient reads
    # better than a noisy "perfect" one.
    return max(0, min(levels, round(value / 255 * levels)))


def main() -> None:
    rows_rgb565 = []
    for y in range(H):
        row = []
        for x in range(W):
            r, g, b = gradient_color(x, y)
            r5 = quantize(r, 31)
            g6 = quantize(g, 63)
            b5 = quantize(b, 31)
            row.append((r5 << 11) | (g6 << 5) | b5)
        rows_rgb565.append(row)

    data_bytes = bytearray()
    for row in rows_rgb565:
        for px in row:
            data_bytes.append(px & 0xFF)
            data_bytes.append((px >> 8) & 0xFF)

    lines = []
    lines.append("/* Generated by assets/gen_bg_gradient.py -- do not hand-edit. */")
    lines.append('#include "lvgl.h"')
    lines.append("")
    lines.append(f"static const uint8_t bg_gradient_map[] = {{")
    for i in range(0, len(data_bytes), 16):
        chunk = data_bytes[i : i + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("const lv_img_dsc_t bg_gradient = {")
    lines.append("    .header.cf = LV_IMG_CF_TRUE_COLOR,")
    lines.append("    .header.always_zero = 0,")
    lines.append(f"    .header.w = {W},")
    lines.append(f"    .header.h = {H},")
    lines.append(f"    .data_size = {len(data_bytes)},")
    lines.append("    .data = bg_gradient_map,")
    lines.append("};")
    lines.append("")

    out_path = r"C:\Users\ysfck\projects\desktop_display\LVGL-BASE\main\images\bg_gradient.c"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", out_path, "bytes:", len(data_bytes))


if __name__ == "__main__":
    main()
