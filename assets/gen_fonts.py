def icon_codepoints() -> dict[str, int]:
    css = (ASSETS / "tabler-icons-outline.css").read_text(encoding="utf-8")
    found = {}
    for macro, name in ICONS.items():
        m = re.search(rf"\.ti-{re.escape(name)}:before\s*\{{\s*content:\s*\"\\([0-9a-f]+)\"", css)
        if not m:
            sys.exit(f"Tabler icon not found in CSS: {name}")
        found[macro] = int(m.group(1), 16)
    return found


def convert(name: str, ttf: str, size: int, glyph_args: list[str]) -> None:
    out = FONTS_DIR / f"{name}.c"
    cmd = [*LV_FONT_CONV, "--font", str(ASSETS / ttf), "--size", str(size), "--bpp", "4",
           "--format", "lvgl", *glyph_args, "--lv-font-name", name, "-o", str(out)]
    print(f"  {name}")
    subprocess.run(cmd, check=True, cwd=ASSETS)
    # lv_font_conv records the absolute output path in the header comment;
    # strip it so regenerating on another machine doesn't churn every file.
    text = out.read_text(encoding="utf-8")
    text = text.replace(str(out), f"main/fonts/{out.name}").replace(str(ASSETS) + "/", "")
    # LVGL is a plain IDF component here, so its header is "lvgl.h".
    text = text.replace('#ifdef LV_LVGL_H_INCLUDE_SIMPLE\n#include "lvgl.h"\n#else\n#include "lvgl/lvgl.h"\n#endif',
                        '#include "lvgl.h"')
    out.write_text(text, encoding="utf-8")


def write_icon_header(codes: dict[str, int]) -> None:
    lines = [
        "#pragma once",
        "",
        "/* Generated by assets/gen_fonts.py -- do not edit by hand.",
        " * Tabler outline icon glyphs; use with ui_theme_font_icon_{18,24,36}(). */",
        "",
        "/* clang-format off */",
    ]
    width = max(len(m) for m in codes)
    for macro, cp in codes.items():
        lines.append(f'#define UI_ICON_{macro.ljust(width)} "\\u{cp:04x}"  /* {ICONS[macro]} */')
    lines += ["/* clang-format on */", ""]
    ICON_HEADER.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    codes = icon_codepoints()
    print("Text fonts:")
    for name, ttf, size, args in TEXT_FONTS:
        convert(name, ttf, size, args)
    print("Icon fonts:")
    icon_range = ",".join(f"0x{cp:x}" for cp in codes.values())
    for size in ICON_SIZES:
        convert(f"tabler_icons_{size}", "tabler-icons-outline.ttf", size, ["-r", icon_range])
    write_icon_header(codes)
    print(f"Wrote {ICON_HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
