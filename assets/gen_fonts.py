"""
Regenerates every LVGL font in main/fonts/ and the icon name header
main/ui_icons.h with lv_font_conv, so fonts are reproducible instead of
hand-run one-offs.

    python3 assets/gen_fonts.py          (needs node / npx on PATH)

Text fonts cover ASCII + Latin-1 + Latin Extended-A (all Turkish letters,
plus the accented names that show up in song titles and chats) and a few
typographic marks. Icons come from the bundled Tabler outline font and are
looked up by name in tabler-icons-outline.css; add a name to ICONS and
rerun to get a new UI_ICON_* macro.
"""

